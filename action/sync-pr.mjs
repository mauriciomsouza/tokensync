/**
 * Commits the files written by `tokensync sync --write` to a branch and opens
 * (or updates) one pull request. Uses git for the commit and the REST API for the PR.
 */
import { execFileSync } from 'node:child_process';
import { appendFileSync, existsSync, readFileSync } from 'node:fs';
import { gh, repo } from './github.mjs';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim();
const branch = process.env.TS_BRANCH || 'tokensync/sync';
const { owner, name } = repo();

if (!git('status', '--porcelain')) {
  console.log('sync produced no changes');
  process.exit(0);
}

const base = (await gh('GET', `/repos/${owner}/${name}`)).default_branch;
git('config', 'user.name', 'github-actions[bot]');
git('config', 'user.email', '41898282+github-actions[bot]@users.noreply.github.com');
git('checkout', '-B', branch);
git('add', '-A');
git('commit', '-m', 'Sync design tokens from Figma', '-m', 'Generated by tokensync sync --write.');
git('push', '--force', 'origin', branch);

const report =
  process.env.TS_REPORT && existsSync(process.env.TS_REPORT) ? readFileSync(process.env.TS_REPORT, 'utf8') : '';
const body = `This PR updates code tokens to match Figma.\n\n${report.replace('<!-- tokensync:report -->', '')}`;
const open = await gh('GET', `/repos/${owner}/${name}/pulls?state=open&head=${owner}:${encodeURIComponent(branch)}`);
const pr = open[0]
  ? await gh('PATCH', `/repos/${owner}/${name}/pulls/${open[0].number}`, { body })
  : await gh('POST', `/repos/${owner}/${name}/pulls`, {
      title: 'Sync design tokens from Figma',
      head: branch,
      base,
      body,
    });
console.log(`Sync PR: ${pr.html_url}`);
if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `url=${pr.html_url}\n`);
